"""Regenerates src/art/assets.ts from the files in assets/art."""
import os

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
A = os.path.join(ROOT, 'assets', 'art')


def block(name, d):
    files = sorted(f for f in os.listdir(os.path.join(A, d)) if f.endswith('.webp'))
    lines = [f"  '{f[:-5]}': require('../../assets/art/{d}/{f}')," for f in files]
    return f"export const {name}: Record<string, number> = {{\n" + "\n".join(lines) + "\n};\n"


out = "/* Generated by tools/art/gen_assets.py — HD illustrations as WebP. */\n\n"
for name, d in [('AVATAR_IMG', 'avatars'), ('GAME_IMG', 'games'), ('ROLE_IMG', 'roles'), ('CARD_IMG', 'cards'), ('UNO_IMG', 'uno'), ('BOARD_IMG', 'boards')]:
    out += block(name, d) + "\n"
out += "export const HERO_IMG: number = require('../../assets/art/hero.webp');\n"
open(os.path.join(ROOT, 'src', 'art', 'assets.ts'), 'w').write(out)
print('assets.ts updated')
