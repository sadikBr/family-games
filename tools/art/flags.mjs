// Renders the country flags of «الأعلام والعواصم» into assets/flags/<code>.webp, and writes
// src/art/flags.ts (the require map the app uses).
//
// Source: the flag-icons set (https://github.com/lipis/flag-icons, MIT licence, © Panayiotis
// Lipiridis — see assets/flags/LICENSE). Get it with `npm pack flag-icons@7.6.0` and unpack it, then:
//   node tools/art/flags.mjs <path to the unpacked package dir>
// Each 4:3 SVG is drawn by Chromium at W×H px and saved as WebP by towebp-flags.py (Pillow).
// Overrides: tools/art/flags/<code>.svg replaces the package's file (a flag that changed since).
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

const here = path.dirname(new URL(import.meta.url).pathname);
const root = path.join(here, '../..');
const pkg = process.argv[2];
if (!pkg || !fs.existsSync(path.join(pkg, 'flags/4x3'))) {
  console.error('usage: node tools/art/flags.mjs <flag-icons package dir>');
  process.exit(1);
}
const W = Number(process.env.FLAG_W ?? 320);
const H = (W * 3) / 4;

// the codes of server/flags-content.ts
const src = fs.readFileSync(path.join(root, 'server/flags-content.ts'), 'utf8');
const codes = [...src.matchAll(/^\s*c\('[a-z]+', '[a-z]+', '([a-z]{2})'/gm)].map((m) => m[1]);
if (codes.length < 190) throw new Error(`only ${codes.length} countries found`);

const require = createRequire(path.join(here, 'package.json'));
let chromium;
try {
  ({ chromium } = require('playwright'));
} catch {
  ({ chromium } = createRequire('/home/claude/fg/tools/art/package.json')('playwright'));
}
const tmp = path.join(here, '.out/flags');
fs.rmSync(tmp, { recursive: true, force: true });
fs.mkdirSync(tmp, { recursive: true });
const browser = await chromium.launch(process.env.CHROME ? { executablePath: process.env.CHROME } : {});
const page = await browser.newPage({ viewport: { width: W, height: H }, deviceScaleFactor: 1 });
for (const code of codes) {
  const own = path.join(here, 'flags', `${code}.svg`);
  const file = fs.existsSync(own) ? own : path.join(pkg, 'flags/4x3', `${code}.svg`);
  let svg = fs.readFileSync(file, 'utf8');
  // draw it at exactly W×H
  svg = svg.replace(/<svg\b([^>]*)>/, (m, attrs) => `<svg${attrs.replace(/\s(width|height)="[^"]*"/g, '')} width="${W}" height="${H}" preserveAspectRatio="none">`);
  await page.setContent(`<!doctype html><html><body style="margin:0;background:transparent">${svg}</body></html>`);
  await page.screenshot({ path: path.join(tmp, `${code}.png`), clip: { x: 0, y: 0, width: W, height: H }, omitBackground: true });
}
await browser.close();
const out = path.join(root, 'assets/flags');
execFileSync('python3', [path.join(here, 'towebp-flags.py'), tmp, out], { stdio: 'inherit' });

const lines = codes
  .slice()
  .sort()
  .map((code) => `  ${/^[a-z]+$/.test(code) && !['do', 'in', 'is'].includes(code) ? code : `'${code}'`}: require('../../assets/flags/${code}.webp'),`);
fs.writeFileSync(
  path.join(root, 'src/art/flags.ts'),
  `/* Generated by tools/art/flags.mjs — the country flags of «الأعلام والعواصم» (flag-icons, MIT). */\n\nexport const FLAG_IMG: Record<string, number> = {\n${lines.join('\n')}\n};\n`,
);
console.log(`${codes.length} flags → assets/flags, src/art/flags.ts`);
