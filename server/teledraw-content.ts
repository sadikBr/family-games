/**
 * `n` different phrases for each of `players`, nobody getting a phrase someone else got, cycling
 * through the whole list across games (the cursor lives in the room's memo).
 */
export function dealPhrases(memo: Map<string, unknown>, players: string[], n: number, shuffle: <T>(a: readonly T[]) => T[]): Record<string, string[]> {
  let pile = (memo.get('teledraw.pile') as string[] | undefined) ?? [];
  const out: Record<string, string[]> = {};
  const given = new Set<string>();
  for (const id of players) {
    const mine: string[] = [];
    while (mine.length < n) {
      if (!pile.length) pile = shuffle(TELEDRAW_PHRASES).filter((p) => !given.has(p));
      const p = pile.pop()!;
      if (!given.has(p)) {
        given.add(p);
        mine.push(p);
      }
    }
    out[id] = mine;
  }
  memo.set('teledraw.pile', pile);
  return out;
}
