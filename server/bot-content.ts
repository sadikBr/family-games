/** category → first letter → words */
export const NAMES_DICT: Record<string, Record<string, string[]>> = Object.fromEntries(
  Object.entries(NAMES_WORDS).map(([cat, words]) => {
    const byLetter: Record<string, string[]> = {};
    for (const w of words) {
      // a word with the article «ال» doesn't count for any letter (see startsWithLetter), so bots skip it
      if (w.startsWith('ال') && w.length > 3) continue;
      (byLetter[norm(w)[0]] ??= []).push(w);
    }
    return [cat, byLetter];
  }),
);

/** Any word starting with a letter (for Hot Potato "words starting with…"). */
export function wordsStartingWith(letter: string): string[] {
  return Object.values(NAMES_DICT).flatMap((m) => m[letter] ?? []);
}

