const LETTER_PROMPT = /بحرف [^\s]+ \(([^)]+)\)/;

/** A word a bot can shout for a Hot Potato topic. */
export function potatoAnswerPool(prompt: string): string[] {
  if (POTATO_ANSWERS[prompt]) return POTATO_ANSWERS[prompt];
  const letter = prompt.match(LETTER_PROMPT)?.[1];
  if (letter) return wordsStartingWith(letter === 'أ' ? 'ا' : letter);
  if (prompt.includes('أولاد')) return Object.values(NAMES_DICT.boy).flat();
  if (prompt.includes('بنات')) return Object.values(NAMES_DICT.girl).flat();
  return ['ممم…'];
}
