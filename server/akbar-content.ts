/**
 * «أكبر أم أصغر؟» — the content: groups of things of one kind measured the same way (country
 * populations, mountain heights, animal speeds…), each item a name in Modern Standard Arabic and a
 * well-known figure. A question pairs two items of the same group only, and never two values closer than
 * the group's `minRatio` (at least 10%: a closer pair would be a coin toss); groups whose figures are
 * estimates that differ between sources (city populations, animal weights, desert areas…) ask for a much
 * wider gap, so a pair can't flip whatever source a player knows.
 *
 * Figures that change carry their year (`asOf`): populations (UN estimates for 2024, Morocco's 2024
 * census), stadium capacities, world records. Years are AD («م»). Owner's rules: Palestine is in, Israel
 * is not; Morocco is always shown with its Sahara (710,850 km²), and the Sahara's cities are Moroccan
 * cities. server/akbar.test.ts checks all of this (units by measure, positive values, the gaps, enough
 * pairs per topic).
 */
import type { AkbarTopic, AkbarUnit } from '../src/shared/games/akbar';

/** What a group measures (each measure has its own units, see MEASURE_UNITS). */
export type AkbarMeasure =
  | 'population'
  | 'area'
  | 'height'
  | 'elevation'
  | 'length'
  | 'depth'
  | 'speed'
  | 'weight'
  | 'lifespan'
  | 'duration'
  | 'year'
  | 'distance'
  | 'capacity'
  | 'count'
  | 'temperature'
  | 'rate';

export const MEASURE_UNITS: Record<AkbarMeasure, AkbarUnit[]> = {
  population: ['people'],
  area: ['km2'],
  height: ['m'],
  elevation: ['m'],
  length: ['km', 'm'],
  depth: ['m'],
  speed: ['kmh'],
  weight: ['kg', 'g'],
  lifespan: ['years'],
  duration: ['days', 'hours'],
  year: ['year'],
  distance: ['km', 'ly', 'm'],
  capacity: ['seats'],
  count: ['players', 'count'],
  temperature: ['celsius'],
  rate: ['bpm'],
};

export interface AkbarItem {
  /** «group:index», unique */
  id: string;
  group: string;
  name: string;
  value: number;
}

export interface AkbarGroup {
  id: string;
  topic: Exclude<AkbarTopic, 'mix'>;
  measure: AkbarMeasure;
  unit: AkbarUnit;
  /** «أيهما أعلى؟» */
  ask: string;
  /** the kind, shown above the question («قمم الجبال») */
  label: string;
  /** the smallest ratio between the two values of a question (≥ 1.1) */
  minRatio: number;
  /** a year question («أيهما أقدم؟»): the smaller year wins */
  older?: boolean;
  /** the year the figures are from, when they change */
  asOf?: number;
  /** rounded estimates («تقريباً») */
  approx?: boolean;
  items: AkbarItem[];
}

type Meta = Omit<AkbarGroup, 'id' | 'items' | 'minRatio'> & { minRatio?: number };

const GROUPS: AkbarGroup[] = [];
function group(id: string, meta: Meta, rows: [string, number][]) {
  GROUPS.push({ id, minRatio: 1.1, ...meta, items: rows.map(([name, value], k) => ({ id: `${id}:${k}`, group: id, name, value })) });
}

