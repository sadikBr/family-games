export const isTextStyle = (cp: number) => TEXT_STYLE.some(([a, b]) => cp >= a && cp <= b);

/** Adds U+FE0F after every text-style emoji (and inside keycaps) that lacks it. */
export function vs16(s: string): string {
  const cps = [...s].map((c) => c.codePointAt(0) as number);
  const out: number[] = [];
  cps.forEach((cp, i) => {
    out.push(cp);
    const next = cps[i + 1];
    if (next === 0xfe0f) return;
    if (isTextStyle(cp) || ((cp === 0x23 || cp === 0x2a || (cp >= 0x30 && cp <= 0x39)) && next === 0x20e3)) out.push(0xfe0f);
  });
  return String.fromCodePoint(...out);
}

