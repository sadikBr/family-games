const TABLE: Record<EmojiCategory, Row[]> = {
  proverbs: PROVERBS,
  movies: MOVIES,
  food: FOOD,
  places: PLACES,
  jobs: JOBS,
  animals: ANIMALS,
  home: HOME,
  sports: SPORTS,
};

function build(): EmojiPuzzle[] {
  const out: EmojiPuzzle[] = [];
  for (const cat of Object.keys(TABLE) as EmojiCategory[]) {
    TABLE[cat].forEach(([emojis, answer, alt, hint, explain, difficulty]) => {
      out.push({
        id: `${cat}:${answer}`,
        cat,
        emojis: vs16(emojis),
        answer,
        alt: alt ? alt.split('|').map((a) => a.trim()).filter(Boolean) : [],
        hint,
        explain: vs16(explain),
        difficulty,
      });
    });
  }
  return out;
}

export const EMOJI_PUZZLES: EmojiPuzzle[] = build();

export const puzzlesOf = (cat: EmojiCategory) => EMOJI_PUZZLES.filter((p) => p.cat === cat);
