function parse(): QamusEntry[] {
  const out: QamusEntry[] = [];
  for (const [cat, text] of Object.entries(RAW) as [QamusCat, string][]) {
    for (const line of text.split('\n')) {
      if (!line.trim()) continue;
      const [word, def, decoys] = line.split('|').map((x) => x.trim());
      out.push({ word, def, cat, decoys: decoys.split('/').map((d) => d.trim()).filter(Boolean) });
    }
  }
  return out;
}

