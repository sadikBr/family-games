/**
 * One opening line for each of `count` stories, never two the same in a game, cycling through the whole
 * list across games before repeating (the cursor lives in the room's memo).
 */
export function dealOpenings(memo: Map<string, unknown>, count: number, shuffle: <T>(a: readonly T[]) => T[]): string[] {
  let pile = (memo.get('story.pile') as string[] | undefined) ?? [];
  const out: string[] = [];
  while (out.length < count) {
    if (!pile.length) pile = shuffle(STORY_OPENINGS).filter((p) => !out.includes(p));
    const p = pile.pop()!;
    if (!out.includes(p)) out.push(p);
  }
  memo.set('story.pile', pile);
  return out;
}
