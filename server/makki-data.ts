/**
 * «مكية أم مدنية؟» — the 114 surahs of the Quran, as the game uses them. Quran content: every value here
 * follows ONE stated convention, and server/makki.test.ts checks the totals against them.
 *
 * Source conventions
 * - Order and names: the order of the Mushaf (1 = الفاتحة … 114 = الناس) and the surah names of مصحف المدينة
 *   النبوية (مجمع الملك فهد لطباعة المصحف الشريف، رواية حفص عن عاصم), written in standard modern spelling as the
 *   Mushaf's index of surahs (فهرس السور) gives them: «سبأ» and «النبأ» (the heading's Uthmani script writes
 *   «سبإ» and «النبإ»), «إبراهيم», «الإنسان», «الانفطار», «الانشقاق» (hamzat al-wasl). The game writes
 *   «سورة …» before the name.
 * - مكية / مدنية: exactly as printed in the surah headings of that Mushaf (which follow the classification of
 *   the Egyptian standard Mushaf of 1342هـ): 28 مدنية, 86 مكية. A whole surah carries one label; the Mushaf's
 *   label does not mention the single verses that some scholars excepted.
 * - Disputed classification (`disputed`): the surahs whose Makki / Madani status is a known difference among
 *   the scholars, from السيوطي، «الإتقان في علوم القرآن»، النوع الأول (the twelve he lists as المختلف فيه,
 *   after أبو الحسن الحصّار: الفاتحة، الرعد، الرحمن، الصف، التغابن، المطففين، القدر، البينة، الزلزلة، الإخلاص،
 *   الفلق، الناس), plus الحج، الإنسان and الكوثر, which he also discusses as disputed. The game still uses the
 *   Mushaf's label and adds «على ما في مصحف المدينة؛ وفيها خلاف» at the reveal.
 * - Verse counts: the Kufan count (العدّ الكوفي), the count of رواية حفص printed in that Mushaf; total 6236.
 * - Juz': the standard division into 30 parts printed in that Mushaf (JUZ_STARTS below: the verse each juz'
 *   begins with). `juz` = the juz' in which the surah's first verse lies.
 * - Facts (`why`: the meaning of the name or why the surah is called so; `theme`: one main theme in one
 *   sentence): only what is well established and agreed (the name's link with a word, a story or the opening
 *   of the surah; the plain subject matter). No virtues, no rewards, no hadith. Where a fact was not certain
 *   it was left out (the field is then absent and the reveal simply omits that line).
 * - `fame`: not Quran content, only the game's difficulty: 1 = surahs most families know well, 2 = well
 *   known, 3 = less often recited outside the khatma. The game opens with famous surahs.
 */

export type Fame = 1 | 2 | 3;

export interface Surah {
  /** its order in the Mushaf, 1–114 */
  n: number;
  /** the name without «سورة» */
  name: string;
  /** as printed in the Madinah Mushaf's heading */
  madani: boolean;
  /** verses, Kufan count */
  ayat: number;
  /** the juz' where it begins (1–30) */
  juz: number;
  fame: Fame;
  /** the meaning of the name / why it is called so */
  why?: string;
  /** one main theme, one sentence */
  theme?: string;
  /** a known difference among scholars on its Makki / Madani status */
  disputed?: boolean;
}

