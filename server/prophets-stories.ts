/**
 * «قصص الأنبياء» — the stories. Each chapter follows the Quranic narrative and only well-established
 * details; the narration is our own wording in Modern Standard Arabic (it is NOT Quran text).
 * When a chapter quotes the Quran, it only gives a reference (`ayah`): the text itself comes from
 * quran-data.json (see prophets-quran.ts), never typed here.
 *
 * Scenes show places and objects only — never prophets, companions or angels.
 */
import type { ProphetsScene, ProphetsStoryId } from '../src/shared/games/prophets';

export interface Chapter {
  title: string;
  scene: ProphetsScene;
  /** 2–4 sentences of narration */
  text: string;
  /** where it is told: [surah name, first verse, last verse] */
  source: [string, number, number][];
  q: string;
  /** the right answer */
  a: string;
  /** 2–3 wrong answers */
  w: string[];
  /** what happened next, shown with the answer */
  after?: string;
  /** a verse (or a short run of verses) to show with the answer: [surah number, from, to?] */
  ayah?: [number, number, number?];
}

export interface Story {
  id: ProphetsStoryId;
  title: string;
  chapters: Chapter[];
  /** 2–3 lessons for the end screen */
  lessons: string[];
}

