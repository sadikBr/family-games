export const ARJAH_PROMPTS: ArjahPrompt[] = ARJAH_THEMES.flatMap((theme) =>
  RAW[theme].map((line, i) => {
    const [tag, clause] = line.split('|');
    return { id: `${theme}-${i + 1}`, theme, tag, clause };
  }),
);

const BY_ID = new Map(ARJAH_PROMPTS.map((p) => [p.id, p]));
export const promptById = (id: string) => BY_ID.get(id);

/** The prompts of a theme setting («منوّع»: all of them). */
export const themePrompts = (theme: ArjahThemeSetting): ArjahPrompt[] => (theme === 'mix' ? ARJAH_PROMPTS : ARJAH_PROMPTS.filter((p) => p.theme === theme));
