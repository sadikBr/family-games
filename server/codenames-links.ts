export interface CodenamesEntry {
  word: string;
  /** the theme the word was listed under (حيوان، طعام، مهنة…), null if none */
  tag: string | null;
  /** related clue words, the strongest first */
  links: string[];
}

function parse(raw: string): CodenamesEntry[] {
  const out: CodenamesEntry[] = [];
  let tag: string | null = null;
  for (const line of raw.split('\n')) {
    const l = line.trim();
    if (!l) continue;
    if (l.startsWith('#')) {
      const t = l.slice(1).trim();
      tag = t === '-' ? null : t;
      continue;
    }
    const i = l.indexOf(':');
    out.push({ word: l.slice(0, i).trim(), tag, links: l.slice(i + 1).trim().split(/\s+/) });
  }
  return out;
}

