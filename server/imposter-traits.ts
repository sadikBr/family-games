const traitsOf = (cat: string, word: string) => TRAITS[cat]?.[word]?.split('|') ?? [];

/** How many words of the category have each trait. */
export function traitCounts(cat: WordCategory): Map<string, number> {
  const counts = new Map<string, number>();
  for (const w of cat.words) for (const t of traitsOf(cat.key, w)) counts.set(t, (counts.get(t) ?? 0) + 1);
  return counts;
}

/** Traits a bot may say, best first. Empty when the word has no traits (the caller falls back). */
export function traitPool(cat: WordCategory, word: string, imposter: boolean): string[] {
  const counts = traitCounts(cat);
  const n = cat.words.length;
  const max = Math.max(3, Math.floor(n / 2)); // «فاكهة» for most of the fruit is a lazy clue
  if (imposter) {
    // a trait that many words share: it fits the real word often enough to pass
    const min = Math.max(3, Math.ceil(n * 0.15));
    return [...counts].filter(([, c]) => c >= min && c <= max).map(([t]) => t);
  }
  const own = traitsOf(cat.key, word);
  const vague = own.filter((t) => (counts.get(t) ?? 0) >= 3 && (counts.get(t) ?? 0) <= max);
  if (vague.length) return vague;
  const shared = own.filter((t) => (counts.get(t) ?? 0) >= 2);
  return shared.length ? shared : own;
}
