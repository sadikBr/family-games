const COLORS: RawabitColor[] = ['yellow', 'green', 'blue', 'purple'];

function parse(raw: Raw, i: number): RawabitPuzzle {
  return {
    id: `r${String(i + 1).padStart(2, '0')}`,
    groups: raw.map((line, k) => {
      const at = line.indexOf(':');
      return {
        color: COLORS[k],
        theme: line.slice(0, at).trim(),
        words: line
          .slice(at + 1)
          .split('،')
          .map((w) => w.trim())
          .filter(Boolean),
      };
    }),
  };
}

export const RAWABIT_PUZZLE_LIST: RawabitPuzzle[] = RAW.map(parse);
