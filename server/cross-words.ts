export type CrossDiff = 'e' | 'm';

export interface CrossWord {
  /** the word as written («أسد») */
  word: string;
  /** its cells' letters joined («اسد») */
  key: string;
  clue: string;
  diff: CrossDiff;
}

function parse(): CrossWord[] {
  const out: CrossWord[] = [];
  for (const raw of RAW.split('\n')) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const [word, clue, d] = line.split('|');
    if (!word || !clue || (d !== 'e' && d !== 'm')) throw new Error(`cross-words: bad line «${line}»`);
    out.push({ word, key: crossKey(word), clue, diff: d });
  }
  return out;
}

/** Every line of the bank. */
export const CROSS_WORDS: CrossWord[] = parse();

/** The bank by key: a word with two meanings has two entries. */
export const CROSS_BY_KEY: Map<string, CrossWord[]> = (() => {
  const m = new Map<string, CrossWord[]>();
  for (const w of CROSS_WORDS) {
    const list = m.get(w.key);
    if (list) {
      // the same meaning twice is a slip; two meanings are welcome
      if (!list.some((x) => x.clue === w.clue)) list.push(w);
    } else m.set(w.key, [w]);
  }
  return m;
})();

