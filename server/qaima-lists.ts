/** `[fame] name / alias / alias` lines → items. */
export function parseItems(text: string): QaimaItem[] {
  return text
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean)
    .map((l) => {
      const m = /^([1-3])\s+(.*)$/.exec(l);
      const [name, ...aliases] = (m ? m[2] : l)
        .split('/')
        .map((s) => s.trim())
        .filter(Boolean);
      return { name, aliases, fame: m ? Number(m[1]) : 2 };
    });
}

type Opts = Omit<QaimaListDef, 'id' | 'title' | 'topic' | 'items'>;
const L = (id: string, title: string, topic: QaimaListDef['topic'], text: string, opts: Opts = {}): QaimaListDef => ({ id, title, topic, items: parseItems(text), ...opts });

