const triviaLabel = (cat: string) => TRIVIA_CATS.find((c) => c.key === cat)?.label ?? '';
const quizLabel = (cat: string) => Q_CATS.find((c) => c.key === cat)?.label ?? '';

/** A loose key for near-duplicates across the two quizzes («من صاحب «المقدمة»؟» asked in both). */
export function dupKey(q: MillionQ): string {
  const n = (s: string) =>
    s
      .replace(/[ً-ٰٟـ]/g, '')
      .replace(/[أإآٱ]/g, 'ا')
      .replace(/ة/g, 'ه')
      .replace(/ى/g, 'ي')
      .replace(/[^\p{L}\p{N}]+/gu, '');
  return `${n(q.a)}|${n(q.q).slice(0, 16)}`;
}

function dedupe(list: MillionQ[]): MillionQ[] {
  const seen = new Set<string>();
  return list.filter((q) => {
    const k = dupKey(q);
    if (seen.has(k) || seen.has(q.q)) return false;
    seen.add(k);
    seen.add(q.q);
    return true;
  });
}

let pools: Record<MillionTopic, MillionQ[][]> | null = null;

/** The questions of a topic split by level: `[lv]` (1–5; index 0 is empty). */
export function millionPools(): Record<MillionTopic, MillionQ[][]> {
  if (pools) return pools;
  const general = dedupe([...TRIVIA.map((t) => ({ q: t.q, a: t.a, w: t.w, lv: levelOf(t.q, t.a), label: triviaLabel(t.cat) })), ...MILLION_EXTRA]);
  const islamic = dedupe(QUESTIONS.map((t) => ({ q: t.q, a: t.a, w: t.w, lv: levelOf(t.q, t.a), label: quizLabel(t.cat) })));
  const split = (list: MillionQ[]) => [0, 1, 2, 3, 4, 5].map((lv) => list.filter((q) => q.lv === lv));
  pools = { general: split(general), islamic: split(islamic), mixed: split(dedupe([...general, ...islamic])) };
  return pools;
}
