/**
 * The judge comes in two halves, line by line (the clue lines and the groups alternate): «dev» to look for
 * missing links while working on the data, «test» kept apart to measure, so that fixing the data cannot simply
 * copy what the measure checks.
 */
export type JudgePart = 'dev' | 'test' | 'all';
/** a word's spelling to compare: normalised, without «ال»; the final «ة» kept («كنز» is not «كنزة», nor «حمام» «حمامة») */
const key = (w: string) => norm(stripAl(w.trim()));

/**
 * A clue without a line of its own is looked up through its consonants (a leading «ا» and the long vowels
 * dropped, three letters at least): «أطفال» → «طفل», «زهور» → «زهر». Stricter than the bot's own form check on
 * purpose: «قصيدة» must not find «صيد», nor «سوق» find «ساق».
 */
const consonants = (w: string) => {
  let s = key(w);
  for (const suffix of ['ات', 'ون', 'ين']) if (s.endsWith(suffix) && s.length >= 5) s = s.slice(0, -2);
  if (s.startsWith('ا') && s.length > 3) s = s.slice(1);
  s = s[0] + s.slice(1).replace(/[اوي]/g, '');
  return s.length >= 3 ? s : `=${key(w)}`;
};

class Judge {
  /** clue stem → the related words (both ways) */
  related = new Map<string, Set<string>>();
  byConsonants = new Map<string, string[]>();
  clueKeys = new Map<string, Set<string>>();
  relate(a: string, b: string) {
    if (key(a) === key(b)) return;
    for (const [x, y] of [[a, b], [b, a]]) {
      const s = this.related.get(key(x)) ?? new Set<string>();
      s.add(y);
      this.related.set(key(x), s);
    }
  }
  index() {
    for (const k of this.related.keys()) {
      const c = consonants(k);
      this.byConsonants.set(c, [...(this.byConsonants.get(c) ?? []), k]);
    }
  }
  /** `lined`: the clue has a line of its own in the whole judge (then its forms' lines are not looked up) */
  has(clue: string, word: string, lined: boolean): boolean {
    let keys = this.clueKeys.get(clue);
    if (!keys) {
      const k = key(clue);
      // a clue with no line of its own: the lines of its singular («أطفال» → «طفل»), never of a longer word
      const near = lined ? [] : (this.byConsonants.get(consonants(clue)) ?? []).filter((s) => s.length <= k.length && k.length - s.length <= 2);
      const lists = [this.related.get(k) ?? new Set<string>(), ...near.map((s) => this.related.get(s)!)];
      keys = new Set(lists.flatMap((l) => [...l].map(key)));
      this.clueKeys.set(clue, keys);
    }
    return keys.has(key(word));
  }
}

const JUDGES: Record<JudgePart, Judge> = { dev: new Judge(), test: new Judge(), all: new Judge() };
let n = 0;
for (const line of RAW.split('\n')) {
  const i = line.indexOf(':');
  if (i < 0) continue;
  const part = n++ % 2 ? JUDGES.test : JUDGES.dev;
  const clue = line.slice(0, i).trim();
  for (const w of line.slice(i + 1).trim().split(/\s+/)) {
    if (!w) continue;
    part.relate(clue, w);
    JUDGES.all.relate(clue, w);
  }
}
for (const line of GROUPS.split('\n')) {
  if (!line.startsWith('=')) continue;
  const part = n++ % 2 ? JUDGES.test : JUDGES.dev;
  const ws = line.slice(1).trim().split(/\s+/);
  for (const a of ws) {
    for (const b of ws) {
      if (a === b) continue;
      part.relate(a, b);
      JUDGES.all.relate(a, b);
    }
  }
}
for (const j of Object.values(JUDGES)) j.index();

/** Does a person, hearing `clue`, think of the board word `word`? (by the hand-written lists above) */
export function judgeRelated(clue: string, word: string, part: JudgePart = 'all'): boolean {
  return JUDGES[part].has(clue, word, JUDGES.all.related.has(key(clue)));
}

/** How many distinct relations (clue ↔ word) the judge holds. */
export function judgeSize(part: JudgePart = 'all'): number {
  let total = 0;
  for (const s of JUDGES[part].related.values()) total += s.size;
  return total / 2;
}
